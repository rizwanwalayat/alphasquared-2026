def ix_flow(ix):
    tabs, panes = [], []
    for i, s in enumerate(ix["steps"]):
        on = " is-on" if i == 0 else ""
        tabs.append(
            '        <button class="ix__step%s" data-ix-tab="%d" type="button">'
            '<span class="ix__step-k">%s</span><span class="ix__step-t">%s</span></button>'
            % (on, i, esc(s["k"]), esc(s["t"])))
        panes.append(
            '        <div class="ix__pane%s" data-ix-pane="%d"><h3>%s</h3><p>%s</p></div>'
            % (on, i, esc(s["t"]), esc(s["d"])))
    return ('      <div class="ix__steps" role="tablist">\n%s\n      </div>\n'
            '      <div class="ix__panes">\n%s\n      </div>'
            % ("\n".join(tabs), "\n".join(panes)))


def ix_screens(ix):
    tabs, panes = [], []
    for i, s in enumerate(ix["shots"]):
        on = " is-on" if i == 0 else ""
        tabs.append('        <button class="ix__tab%s" data-ix-tab="%d" type="button">%s</button>'
                    % (on, i, esc(s["t"])))
        panes.append(
            '        <figure class="ix__pane%s" data-ix-pane="%d">\n'
            '          <img src="../%s/%s" alt="%s" loading="lazy" decoding="async" />\n'
            '          <figcaption>%s</figcaption>\n        </figure>'
            % (on, i, IMG_HREF, s["img"], attr(s["alt"]), esc(s["cap"])))
    return ('      <div class="ix__tabs" role="tablist">\n%s\n      </div>\n'
            '      <div class="ix__panes ix__panes--shots">\n%s\n      </div>'
            % ("\n".join(tabs), "\n".join(panes)))


def ix_metrics(ix):
    rows = []
    for m in ix["items"]:
        rows.append(
            '        <div class="ix__meter" style="--p:%s">\n'
            '          <div class="ix__meter-n" data-count="%s" data-suffix="%s">0%s</div>\n'
            '          <div class="ix__meter-l">%s</div>\n'
            '          <div class="ix__meter-bar"><i></i></div>\n        </div>'
            % (m["p"], m["n"], attr(m["suffix"]), esc(m["suffix"]), esc(m["l"])))
    return '      <div class="ix__meters">\n%s\n      </div>' % "\n".join(rows)


