def page_title(p):
    """Search results truncate around 65 characters, so drop the tagline
    rather than ship a title nobody sees the end of."""
    if p["title"]:
        return p["title"]
    suffix = " | Alpha Squared"
    full = "%s: %s%s" % (p["name"], p["tagline"].rstrip("."), suffix)
    if len(full) <= 65:
        return full
    short = "%s Case Study%s" % (p["name"], suffix)
    return short if len(short) <= 65 else p["name"] + suffix


