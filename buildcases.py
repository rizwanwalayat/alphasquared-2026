CARD = """      <article class="work" data-anim="up"{delay}>
        <a class="work__link" href="case-studies/{slug}.html">
          <div class="work__shot">
            <img src="{href}/{image}" alt="{alt}" loading="lazy" decoding="async" />
          </div>
          <div class="work__body">
            <span class="badge">{category}</span>
            <h3>{name}</h3>
            <p>{desc}</p>
            <span class="tlink">Read the case study <i class="ar">&rarr;</i></span>
          </div>
        </a>
      </article>"""


def render_grid(projects):
    cards = []
    for i, p in enumerate(projects):
        column = i % 3
        cards.append(CARD.format(
            delay="" if column == 0 else ' data-delay="%.2f"' % (0.08 * column),
            slug=p["slug"], href=IMG_HREF, image=p["images"][0][0],
            alt=attr(p["images"][0][1]), category=esc(p["category"]),
            name=esc(p["name"]), desc=esc(p["card"])))
    return "\n\n".join(cards)


# ──────────────────────────────── sitemap ────────────────────────────────────

def render_sitemap(projects):
    today = datetime.date.today().isoformat()
    urls = []
    for page, priority in STATIC_PAGES:
        loc = "%s/" % SITE if page == "index.html" else "%s/%s" % (SITE, page)
        urls.append("  <url>\n    <loc>%s</loc>\n    <lastmod>%s</lastmod>\n"
                    "    <changefreq>monthly</changefreq>\n    <priority>%s</priority>\n  </url>"
                    % (loc, today, priority))
    for p in projects:
        urls.append("  <url>\n    <loc>%s/case-studies/%s.html</loc>\n    <lastmod>%s</lastmod>\n"
                    "    <changefreq>yearly</changefreq>\n    <priority>0.7</priority>\n  </url>"
                    % (SITE, p["slug"], today))
    return ('<?xml version="1.0" encoding="UTF-8"?>\n'
            '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n'
            + "\n".join(urls) + "\n</urlset>\n")


