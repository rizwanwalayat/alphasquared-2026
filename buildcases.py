def load_projects():
    """casedata.PROJECTS, or the JSON export when --from-json is passed."""
    if "--from-json" not in sys.argv:
        return casedata.PROJECTS, casedata.FLAGSHIP

    if not os.path.exists(EXPORT):
        raise SystemExit("missing %s; run 'python exportcases.py' first" % EXPORT)

    with open(EXPORT, encoding="utf-8") as fh:
        records = json.load(fh)

    records = [r for r in records if r.get("published", True)]
    records.sort(key=lambda r: r.get("order", 0))
    for r in records:
        # JSON has no tuples, and the templates unpack (file, alt).
        r["images"] = [tuple(img) for img in r["images"]]

    flagship = tuple(r["slug"] for r in records if r.get("flagship"))
    return records, flagship


def main():
    projects, flagship = load_projects()
    for p in projects:
        missing = [f for f, _ in p["images"] if not os.path.exists(os.path.join(IMG_DIR, f))]
        if missing:
            raise SystemExit("%s references missing images: %s" % (p["slug"], missing))

    if not os.path.isdir(OUT_DIR):
        os.makedirs(OUT_DIR)

    written = 0
    for i, p in enumerate(projects):
        if p["hand"]:
            continue
        prev_p = projects[i - 1]
        next_p = projects[(i + 1) % len(projects)]
        path = os.path.join(OUT_DIR, "%s.html" % p["slug"])
        with open(path, "w", encoding="utf-8", newline="\n") as fh:
            fh.write(render_page(p, prev_p, next_p))
        written += 1

    grid = [p for p in projects if p["slug"] not in flagship]
    with open(INDEX, encoding="utf-8") as fh:
        page = fh.read()
    if START not in page or END not in page:
        raise SystemExit("work markers not found in case-studies.html")
    block = "%s\n%s\n      %s" % (START, render_grid(grid), END)
    page = re.sub(re.escape(START) + r".*?" + re.escape(END), lambda _: block, page, flags=re.S)
    with open(INDEX, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(page)

    with open(SITEMAP, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(render_sitemap(projects))

    print("generated %d detail pages, %d index cards, %d sitemap URLs"
          % (written, len(grid), len(projects) + len(STATIC_PAGES)))


if __name__ == "__main__":
    main()
